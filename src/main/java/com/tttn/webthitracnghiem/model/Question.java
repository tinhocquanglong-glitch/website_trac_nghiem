package com.tttn.webthitracnghiem.model;
import org.hibernate.annotations.NotFoundAction;
import org.hibernate.annotations.NotFound;

import com.fasterxml.jackson.annotation.JsonBackReference;
import com.fasterxml.jackson.annotation.JsonManagedReference;
import com.fasterxml.jackson.annotation.JsonIgnore;
import org.springframework.stereotype.Component;

import javax.persistence.*;
import java.util.List;
import java.util.Set;

@Entity
@Component
public class Question {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private int quesId;
    @Column(columnDefinition = "text")
    private String title;
    private String optionA;
    private String optionB;
    private String optionC;
    private String optionD;
    private int ans;
    private int chose;
    private int level;
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "lesson_id",referencedColumnName = "id")
    @NotFound(action = NotFoundAction.IGNORE)
    @JsonBackReference
    private Lesson lesson;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "lesson_plan_lesson_id")
    @NotFound(action = NotFoundAction.IGNORE)
    @JsonIgnore
    private LessonPlanLesson lessonPlanLesson;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "subject_id")
    @NotFound(action = NotFoundAction.IGNORE)
    @JsonIgnore
    private Subject subject;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "class_id")
    @NotFound(action = NotFoundAction.IGNORE)
    @JsonIgnore
    private Classes classes;
    @ManyToMany(mappedBy = "questions")
    @JsonManagedReference
    private Set<Exam> exams;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "school_id")
    @NotFound(action = NotFoundAction.IGNORE)
    private School school;

    @Column(name = "is_public")
    private Boolean isPublic = true;

    public static final String SOURCE_MANUAL = "MANUAL";
    public static final String SOURCE_EXCEL = "EXCEL";
    public static final String SOURCE_AI = "AI";
    public static final String REVIEW_APPROVED = "APPROVED";
    public static final String REVIEW_PENDING = "PENDING";

    @Column(name = "source", length = 20)
    private String source;

    // PENDING questions (e.g. generated by AI) stay out of exams until a teacher approves them.
    @Column(name = "review_status", length = 20)
    private String reviewStatus;

    // Lesson-plan lesson whose content produced this question; a plain id so deleting the plan never blocks.
    @Column(name = "source_plan_lesson_id")
    private Integer sourcePlanLessonId;

    @Column(name = "status")
    private Integer status = 1;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "author_id")
    @NotFound(action = NotFoundAction.IGNORE)
    @JsonIgnore
    private User author;

    public Question() {
        super();
    }

    public Question(int quesId, String title, String optionA, String optionB, String optionC, String optionD, int ans, int chose, int level, Lesson lesson, Set<Exam> exams) {
        this.quesId = quesId;
        this.title = title;
        this.optionA = optionA;
        this.optionB = optionB;
        this.optionC = optionC;
        this.optionD = optionD;
        this.ans = ans;
        this.chose = chose;
        this.level = level;
        this.lesson = lesson;
        this.exams = exams;
    }

    public int getLevel() {
        return level;
    }

    public void setLevel(int level) {
        this.level = level;
    }

    public Lesson getLesson() {
        return lesson;
    }

    public void setLesson(Lesson lesson) {
        this.lesson = lesson;
    }

    public LessonPlanLesson getLessonPlanLesson() {
        return lessonPlanLesson;
    }

    public void setLessonPlanLesson(LessonPlanLesson lessonPlanLesson) {
        this.lessonPlanLesson = lessonPlanLesson;
    }

    public int getQuesId() {
        return quesId;
    }

    public void setQuesId(int quesId) {
        this.quesId = quesId;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getOptionA() {
        return optionA;
    }

    public void setOptionA(String optionA) {
        this.optionA = optionA;
    }

    public String getOptionB() {
        return optionB;
    }

    public void setOptionB(String optionB) {
        this.optionB = optionB;
    }

    public String getOptionC() {
        return optionC;
    }

    public void setOptionC(String optionC) {
        this.optionC = optionC;
    }

    public int getAns() {
        return ans;
    }

    public void setAns(int ans) {
        this.ans = ans;
    }

    public int getChose() {
        return chose;
    }

    public String getOptionD() {
        return optionD;
    }

    public void setOptionD(String optionD) {
        this.optionD = optionD;
    }

    public void setChose(int chose) {
        this.chose = chose;
    }

    public Set<Exam> getExams() {
        return exams;
    }

    public void setExams(Set<Exam> exams) {
        this.exams = exams;
    }

    public School getSchool() {
        return school;
    }

    public void setSchool(School school) {
        this.school = school;
    }

    public Boolean getIsPublic() {
        return isPublic;
    }

    public void setIsPublic(Boolean isPublic) {
        this.isPublic = isPublic;
    }

    public String getSource() {
        return source;
    }

    public void setSource(String source) {
        this.source = source;
    }

    public String getReviewStatus() {
        return reviewStatus;
    }

    public void setReviewStatus(String reviewStatus) {
        this.reviewStatus = reviewStatus;
    }

    /** Old rows have no status and count as approved. */
    public boolean isApproved() {
        return reviewStatus == null || REVIEW_APPROVED.equals(reviewStatus);
    }

    public Integer getSourcePlanLessonId() {
        return sourcePlanLessonId;
    }

    public void setSourcePlanLessonId(Integer sourcePlanLessonId) {
        this.sourcePlanLessonId = sourcePlanLessonId;
    }

    public User getAuthor() {
        return author;
    }

    public void setAuthor(User author) {
        this.author = author;
    }

    public Subject getSubject() {
        return subject;
    }

    public void setSubject(Subject subject) {
        this.subject = subject;
    }

    public Classes getClasses() {
        return classes;
    }

    public void setClasses(Classes classes) {
        this.classes = classes;
    }

    public Integer getStatus() {
        return status;
    }

    public void setStatus(Integer status) {
        this.status = status;
    }

    public boolean isActive() {
        return status == null || status == 1;
    }
}